#!/usr/bin/env bash
# HongSSH WebRTC signaling relay - one-file Linux deployment.
#
# The script is self-contained: it installs Node.js, writes relay-server.js,
# creates a systemd service, generates a HOST_TOKEN on first run, and starts
# the relay. Re-running it updates the service and preserves the generated
# token unless --token is supplied.
#
# relay-server.js is embedded below. If relay-server.js changes, regenerate this
# file so the embedded copy is current.
#
# Supported: Debian/Ubuntu, RHEL/Rocky/Alma/CentOS/Fedora, Amazon Linux.
#
# Usage:
#   sudo bash deploy-relay.sh
#   sudo bash deploy-relay.sh --port 47891 --token 'your-token'
#   sudo bash deploy-relay.sh --tls-cert /path/fullchain.pem --tls-key /path/privkey.pem
#   sudo bash deploy-relay.sh --ice-json '[{"urls":"stun:stun.example.com:3478"}]'

set -Eeuo pipefail

INSTALL_DIR="/opt/hongssh-relay"
ENV_FILE="/etc/hongssh-relay.env"
TLS_DIR="/etc/hongssh-relay/tls"
SERVICE_NAME="hongssh-relay"
SERVICE_FILE="/etc/systemd/system/${SERVICE_NAME}.service"
SERVICE_USER="hongssh-relay"
DEFAULT_ICE='[{"urls":"stun:stun.l.google.com:19302"}]'

show_help() {
  cat <<'EOF'
HongSSH signaling relay deployment

Usage:
  sudo bash deploy-relay.sh [options]

Options:
  --port <port>          Signaling port (default: 47891)
  --token <token>        HOST_TOKEN; generated if omitted
  --ice-json <json>      ICE_SERVERS_JSON, e.g. '[{"urls":"stun:host:3478"}]'
  --tls-cert <path>      PEM certificate chain for direct WSS
  --tls-key <path>       PEM private key for direct WSS
  --no-tls               Disable direct TLS (use a reverse proxy instead)
  --no-firewall          Do not open the signaling port in ufw/firewalld
  -h, --help             Show this help

Without TLS, use a reverse proxy (Caddy/Nginx) for public WSS, or configure
--tls-cert/--tls-key if the server already has certificates.

The script deploys the current Node.js signaling relay from this repository.
EOF
}

for arg in "$@"; do
  case "$arg" in
    -h|--help) show_help; exit 0 ;;
  esac
done

if [[ "${EUID:-$(id -u)}" -ne 0 ]]; then
  if command -v sudo >/dev/null 2>&1; then
    SCRIPT_PATH="$(cd "$(dirname "$0")" >/dev/null 2>&1 && pwd)/$(basename "$0")"
    exec sudo -- bash "$SCRIPT_PATH" "$@"
  fi
  echo "ERROR: run as root or install sudo." >&2
  exit 1
fi

PORT_ARG=""
TOKEN_ARG=""
ICE_ARG=""
TLS_CERT_ARG=""
TLS_KEY_ARG=""
DISABLE_TLS=0
OPEN_FIREWALL=1
ENV_PORT="${PORT:-}"
ENV_TOKEN="${HOST_TOKEN:-}"
ENV_ICE="${ICE_SERVERS_JSON:-}"
ENV_TLS_CERT="${TLS_CERT:-}"
ENV_TLS_KEY="${TLS_KEY:-}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --port)
      [[ $# -ge 2 && -n "${2:-}" ]] || { echo "ERROR: --port requires a value" >&2; exit 1; }
      PORT_ARG="${2:-}"
      shift 2
      ;;
    --token)
      [[ $# -ge 2 && -n "${2:-}" ]] || { echo "ERROR: --token requires a value" >&2; exit 1; }
      TOKEN_ARG="${2:-}"
      shift 2
      ;;
    --ice-json)
      [[ $# -ge 2 && -n "${2:-}" ]] || { echo "ERROR: --ice-json requires a value" >&2; exit 1; }
      ICE_ARG="${2:-}"
      shift 2
      ;;
    --tls-cert)
      [[ $# -ge 2 && -n "${2:-}" ]] || { echo "ERROR: --tls-cert requires a value" >&2; exit 1; }
      TLS_CERT_ARG="${2:-}"
      shift 2
      ;;
    --tls-key)
      [[ $# -ge 2 && -n "${2:-}" ]] || { echo "ERROR: --tls-key requires a value" >&2; exit 1; }
      TLS_KEY_ARG="${2:-}"
      shift 2
      ;;
    --no-tls)
      DISABLE_TLS=1
      shift
      ;;
    --no-firewall)
      OPEN_FIREWALL=0
      shift
      ;;
    *)
      echo "ERROR: unknown option: $1 (use --help)" >&2
      exit 1
      ;;
  esac
done

log() { printf '\033[1;32m[hongssh]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[hongssh]\033[0m %s\n' "$*" >&2; }
die() { printf '\033[1;31m[hongssh] ERROR:\033[0m %s\n' "$*" >&2; exit 1; }

# Preserve existing settings on a re-run. The file is generated by this script
# with root-only permissions.
if [[ -f "$ENV_FILE" ]]; then
  set -a
  # shellcheck disable=SC1090
  . "$ENV_FILE"
  set +a
fi

PORT="${PORT_ARG:-${ENV_PORT:-${PORT:-47891}}}"
TOKEN="${TOKEN_ARG:-${ENV_TOKEN:-${HOST_TOKEN:-}}}"
ICE_JSON="${ICE_ARG:-${ENV_ICE:-${ICE_SERVERS_JSON:-$DEFAULT_ICE}}}"
TLS_CERT_SOURCE="${TLS_CERT_ARG:-${ENV_TLS_CERT:-${TLS_CERT:-}}}"
TLS_KEY_SOURCE="${TLS_KEY_ARG:-${ENV_TLS_KEY:-${TLS_KEY:-}}}"
if [[ "$DISABLE_TLS" -eq 1 ]]; then
  TLS_CERT_SOURCE=""
  TLS_KEY_SOURCE=""
fi

[[ "$PORT" =~ ^[0-9]+$ ]] || die "invalid port: $PORT"
((PORT >= 1 && PORT <= 65535)) || die "port out of range: $PORT"
[[ -z "${ICE_JSON//[[:space:]]/}" ]] && ICE_JSON="$DEFAULT_ICE"
[[ "$ICE_JSON" != *"'"* ]] || die "ICE JSON must not contain single quotes"
[[ "$ICE_JSON" != *$'\n'* ]] || die "ICE JSON must be a single line"
if [[ -n "$TLS_CERT_SOURCE" || -n "$TLS_KEY_SOURCE" ]]; then
  [[ -n "$TLS_CERT_SOURCE" && -n "$TLS_KEY_SOURCE" ]] || die \
    "both --tls-cert and --tls-key are required for direct TLS"
  [[ "$TLS_CERT_SOURCE" != *"'"* && "$TLS_KEY_SOURCE" != *"'"* ]] || die \
    "TLS certificate/key paths must not contain single quotes"
  [[ "$TLS_CERT_SOURCE" != *$'\n'* && "$TLS_KEY_SOURCE" != *$'\n'* ]] || die \
    "TLS certificate/key paths must be single-line"
fi

command -v systemctl >/dev/null 2>&1 || die "systemd is required"
[[ -d /run/systemd/system ]] || die "systemd is not running as PID 1; this script needs a systemd Linux host"

if [[ ! -r /etc/os-release ]]; then
  die "cannot read /etc/os-release; unsupported Linux distribution"
fi
# shellcheck disable=SC1091
. /etc/os-release
OS_ID="${ID:-}"
OS_LIKE="${ID_LIKE:-}"

install_base_packages() {
  if command -v apt-get >/dev/null 2>&1; then
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -y
    apt-get install -y curl ca-certificates openssl gnupg
  elif command -v dnf >/dev/null 2>&1; then
    dnf install -y curl ca-certificates openssl gnupg2
  elif command -v yum >/dev/null 2>&1; then
    yum install -y curl ca-certificates openssl gnupg2
  else
    die "unsupported package manager (need apt-get, dnf or yum)"
  fi
}

node_major() {
  "$1" -p "Number(process.versions.node.split('.')[0])" 2>/dev/null || echo 0
}

install_distro_node() {
  if command -v apt-get >/dev/null 2>&1; then
    apt-get install -y nodejs npm
  elif command -v dnf >/dev/null 2>&1; then
    dnf install -y nodejs npm
  elif command -v yum >/dev/null 2>&1; then
    yum install -y nodejs npm
  else
    return 1
  fi
}

install_node() {
  if command -v node >/dev/null 2>&1 && [[ "$(node_major "$(command -v node)")" -ge 20 ]]; then
    return 0
  fi
  log "Trying Node.js from the distribution packages"
  install_distro_node || warn "distribution Node.js packages were not available"
  if command -v node >/dev/null 2>&1 && [[ "$(node_major "$(command -v node)")" -ge 20 ]]; then
    log "Using distro Node.js $(node -v)"
    return 0
  fi
  log "Installing Node.js 20 LTS from NodeSource"
  case "${OS_ID} ${OS_LIKE}" in
    *debian*|*ubuntu*)
      curl -fsSL https://deb.nodesource.com/setup_20.x -o /tmp/hongssh-nodesource.sh
      bash /tmp/hongssh-nodesource.sh
      apt-get install -y nodejs
      ;;
    *rhel*|*centos*|*rocky*|*alma*|*fedora*|*amzn*)
      curl -fsSL https://rpm.nodesource.com/setup_20.x -o /tmp/hongssh-nodesource.sh
      bash /tmp/hongssh-nodesource.sh
      if command -v dnf >/dev/null 2>&1; then dnf install -y nodejs; else yum install -y nodejs; fi
      ;;
    *)
      die "unsupported distribution '$OS_ID'; install Node.js 20+ manually"
      ;;
  esac
  rm -f /tmp/hongssh-nodesource.sh
}

install_base_packages
if [[ -z "$TOKEN" ]]; then
  TOKEN="$(openssl rand -hex 32 2>/dev/null || true)"
fi
[[ -n "$TOKEN" ]] || die "could not generate HOST_TOKEN; pass --token"
[[ "$TOKEN" =~ ^[A-Za-z0-9._~+/=-]{16,128}$ ]] || die \
  "HOST_TOKEN must be 16-128 characters using A-Z a-z 0-9 . _ ~ + / = -"
if command -v node >/dev/null 2>&1 && [[ "$(node_major "$(command -v node)")" -ge 20 ]]; then
  NODE_BIN="$(command -v node)"
  log "Using existing Node.js $(node -v)"
else
  install_node
  NODE_BIN="$(command -v node || true)"
  [[ -n "$NODE_BIN" ]] || die "Node.js installation did not provide node"
  [[ "$(node_major "$NODE_BIN")" -ge 20 ]] || die "Node.js 20+ is required"
fi
command -v npm >/dev/null 2>&1 || die "npm is required"
NODE_REAL="$(readlink -f "$NODE_BIN" 2>/dev/null || echo "$NODE_BIN")"
case "$NODE_REAL" in
  /usr/*|/opt/*) ;;
  *) die "Node.js at $NODE_REAL is outside /usr or /opt and may not be readable by the service user; install a system-wide Node.js" ;;
esac

"$NODE_BIN" -e '
  const value = JSON.parse(process.argv[1]);
  if (!Array.isArray(value)) process.exit(1);
  for (const item of value) {
    if (!item || (typeof item.urls !== "string" && !Array.isArray(item.urls))) process.exit(1);
  }
' "$ICE_JSON" >/dev/null 2>&1 || die "ICE_SERVERS_JSON is not a valid ICE server array"

if ! id -u "$SERVICE_USER" >/dev/null 2>&1; then
  useradd --system --home-dir "$INSTALL_DIR" --shell /usr/sbin/nologin "$SERVICE_USER"
fi

install -d -m 0750 -o root -g "$SERVICE_USER" "$INSTALL_DIR"
install -d -m 0750 -o root -g "$SERVICE_USER" /etc/hongssh-relay
if [[ -n "$TLS_CERT_SOURCE" ]]; then
  install -d -m 0750 -o root -g "$SERVICE_USER" "$TLS_DIR"
  [[ -r "$TLS_CERT_SOURCE" ]] || die "cannot read TLS certificate: $TLS_CERT_SOURCE"
  [[ -r "$TLS_KEY_SOURCE" ]] || die "cannot read TLS private key: $TLS_KEY_SOURCE"
  if [[ "$(readlink -f "$TLS_CERT_SOURCE")" != "$(readlink -f "$TLS_DIR/fullchain.pem")" ]]; then
    install -m 0640 -o root -g "$SERVICE_USER" "$TLS_CERT_SOURCE" "$TLS_DIR/fullchain.pem"
  else
    chown root:"$SERVICE_USER" "$TLS_DIR/fullchain.pem"
    chmod 0640 "$TLS_DIR/fullchain.pem"
  fi
  if [[ "$(readlink -f "$TLS_KEY_SOURCE")" != "$(readlink -f "$TLS_DIR/privkey.pem")" ]]; then
    install -m 0640 -o root -g "$SERVICE_USER" "$TLS_KEY_SOURCE" "$TLS_DIR/privkey.pem"
  else
    chown root:"$SERVICE_USER" "$TLS_DIR/privkey.pem"
    chmod 0640 "$TLS_DIR/privkey.pem"
  fi
  TLS_CERT_FINAL="$TLS_DIR/fullchain.pem"
  TLS_KEY_FINAL="$TLS_DIR/privkey.pem"
else
  TLS_CERT_FINAL=""
  TLS_KEY_FINAL=""
fi

log "Writing relay server"
umask 022
cat >"$INSTALL_DIR/relay-server.js" <<'HONGSSH_RELAY_SERVER_EOF'
'use strict'

/**
 * HongSSH WebRTC signaling relay.
 *
 * It only exchanges SDP/ICE and device presence. Screen, input and file data
 * travel over the WebRTC DataChannel between the two desktop apps. When ICE
 * cannot find a direct path, a TURN server (configured below) carries the data;
 * this process never proxies media.
 *
 * Environment:
 *   PORT=47891
 *   HOST_TOKEN=change-me
 *   ICE_SERVERS_JSON=[{"urls":"stun:stun.example.com:3478"}]
 *   TLS_CERT=/etc/hongssh/fullchain.pem
 *   TLS_KEY=/etc/hongssh/privkey.pem
 */

const fs = require('node:fs')
const http = require('node:http')
const https = require('node:https')
const crypto = require('node:crypto')
const { WebSocketServer, WebSocket } = require('ws')

const PORT = Number(process.env.PORT) || 47891
const HOST_TOKEN = String(process.env.HOST_TOKEN || '').trim()
const TLS_CERT = process.env.TLS_CERT || ''
const TLS_KEY = process.env.TLS_KEY || ''
const configuredIce = parseIceServers(process.env.ICE_SERVERS_JSON)
const ICE_SERVERS = configuredIce.length
  ? configuredIce
  : [{ urls: 'stun:stun.l.google.com:19302' }]

if (!HOST_TOKEN) {
  console.error('HOST_TOKEN is required; refusing to start an unauthenticated relay.')
  process.exit(1)
}

function parseIceServers(value) {
  if (!value) return []
  try {
    const parsed = JSON.parse(value)
    return Array.isArray(parsed) ? parsed : []
  } catch (error) {
    console.error('ICE_SERVERS_JSON is not valid JSON:', error.message)
    return []
  }
}

function safeEqual(a, b) {
  const left = Buffer.from(String(a || ''))
  const right = Buffer.from(String(b || ''))
  if (left.length !== right.length) return false
  return crypto.timingSafeEqual(left, right)
}

function validDevice(value) {
  return /^[A-Za-z0-9-]{6,32}$/.test(String(value || ''))
}

function json(ws, value) {
  if (ws && ws.readyState === WebSocket.OPEN) ws.send(JSON.stringify(value))
}

const agents = new Map()
const sessions = new Map()

function closeSession(sessionId, reason) {
  const session = sessions.get(sessionId)
  if (!session) return
  sessions.delete(sessionId)
  clearTimeout(session.timer)
  for (const socket of [session.controller, session.agentSocket]) {
    try {
      if (socket && socket.readyState === WebSocket.OPEN) socket.close(1000, reason || 'closed')
    } catch {}
  }
  if (session.agent?.ws === session.agentControl) {
    json(session.agentControl, { type: 'peer-closed', sessionId })
  }
}

function handleAgent(ws, request, device) {
  if (!HOST_TOKEN || !safeEqual(request.headers['x-relay-token'], HOST_TOKEN)) {
    ws.close(4003, 'invalid host token')
    return
  }
  const existing = agents.get(device)
  if (existing && existing.ws !== ws) {
    try {
      existing.ws.close(4001, 'agent replaced')
    } catch {}
    for (const session of [...sessions.values()]) {
      if (session.agent === existing) closeSession(session.id, 'agent replaced')
    }
  }
  const agent = { device, ws, sessions: new Set(), address: request.socket.remoteAddress || '' }
  agents.set(device, agent)
  json(ws, { type: 'registered', device, iceServers: ICE_SERVERS })
  console.log(`[agent] ${device} online from ${agent.address} (${agents.size} online)`)
  ws.on('message', (data) => {
    let message
    try {
      message = JSON.parse(String(data))
    } catch {
      return
    }
    if (message.type === 'pong') return
  })
  ws.on('close', () => {
    if (agents.get(device) === agent) agents.delete(device)
    for (const session of [...sessions.values()]) {
      if (session.agent === agent) closeSession(session.id, 'agent offline')
    }
    console.log(`[agent] ${device} offline (${agents.size} online)`)
  })
  ws.on('error', (error) => console.warn(`[agent] ${device} error:`, error.message))
}

function handleControl(ws, request, device) {
  const agent = agents.get(device)
  if (!agent) {
    ws.close(4004, 'device offline')
    return
  }
  if ([...sessions.values()].some((session) => session.agent === agent)) {
    ws.close(4009, 'device busy')
    return
  }
  const sessionId = crypto.randomBytes(12).toString('hex')
  const session = {
    id: sessionId,
    device,
    agent,
    agentControl: agent.ws,
    controller: ws,
    agentSocket: null,
    timer: setTimeout(() => closeSession(sessionId, 'agent session timeout'), 15000)
  }
  sessions.set(sessionId, session)
  agent.sessions.add(sessionId)
  json(agent.ws, { type: 'peer', sessionId, iceServers: ICE_SERVERS })
  json(ws, { type: 'peer-ready', sessionId, iceServers: ICE_SERVERS })
  console.log(`[session] ${device} waiting for agent ${sessionId}`)
  ws.on('message', (data) => forward(session, 'controller', data))
  ws.on('close', () => closeSession(sessionId, 'controller closed'))
  ws.on('error', () => closeSession(sessionId, 'controller error'))
}

function handleAgentSession(ws, request, device, sessionId) {
  const session = sessions.get(sessionId)
  if (!session || session.device !== device) {
    ws.close(4004, 'session not found')
    return
  }
  if (!HOST_TOKEN || !safeEqual(request.headers['x-relay-token'], HOST_TOKEN)) {
    ws.close(4003, 'invalid host token')
    return
  }
  if (session.agentSocket) {
    ws.close(4009, 'session already attached')
    return
  }
  session.agentSocket = ws
  clearTimeout(session.timer)
  session.timer = null
  console.log(`[session] ${device} paired ${sessionId}`)
  ws.on('message', (data) => forward(session, 'agent', data))
  ws.on('close', () => closeSession(sessionId, 'agent session closed'))
  ws.on('error', () => closeSession(sessionId, 'agent session error'))
}

function forward(session, from, data) {
  const target = from === 'agent' ? session.controller : session.agentSocket
  if (!target || target.readyState !== WebSocket.OPEN) return
  try {
    target.send(data)
  } catch {}
}

const server = TLS_CERT && TLS_KEY
  ? https.createServer({ cert: fs.readFileSync(TLS_CERT), key: fs.readFileSync(TLS_KEY) })
  : http.createServer()

server.on('request', (request, response) => {
  if (request.url === '/health') {
    response.writeHead(200, { 'content-type': 'application/json' })
    response.end(JSON.stringify({ ok: true, agents: agents.size, sessions: sessions.size }))
    return
  }
  response.writeHead(404)
  response.end()
})

const wss = new WebSocketServer({ server, maxPayload: 1024 * 1024 })
wss.on('connection', (ws, request) => {
  const url = new URL(request.url, 'http://localhost')
  if (url.pathname !== '/signal') {
    ws.close(4004, 'not found')
    return
  }
  const role = url.searchParams.get('role') || ''
  const device = String(url.searchParams.get('device') || '')
  const sessionId = url.searchParams.get('session') || ''
  if (!validDevice(device)) {
    ws.close(4000, 'invalid device id')
    return
  }
  if (role === 'host') {
    handleAgent(ws, request, device)
  } else if (role === 'control') {
    handleControl(ws, request, device)
  } else if (role === 'agent-session') {
    handleAgentSession(ws, request, device, sessionId)
  } else {
    ws.close(4000, 'invalid role')
  }
})

const heartbeat = setInterval(() => {
  for (const ws of wss.clients) {
    if (ws.isAlive === false) {
      ws.terminate()
      continue
    }
    ws.isAlive = false
    try {
      ws.ping()
    } catch {}
  }
}, 30000)
wss.on('connection', (ws) => {
  ws.isAlive = true
  ws.on('pong', () => {
    ws.isAlive = true
  })
})

server.listen(PORT, '0.0.0.0', () => {
  console.log(`HongSSH signaling relay listening on ${TLS_CERT && TLS_KEY ? 'wss' : 'ws'}://0.0.0.0:${PORT}/signal`)
  console.log(`ICE servers: ${ICE_SERVERS.length}`)
})

process.on('SIGTERM', () => {
  clearInterval(heartbeat)
  for (const session of [...sessions.values()]) closeSession(session.id, 'server shutdown')
  server.close(() => process.exit(0))
})

HONGSSH_RELAY_SERVER_EOF
chown root:"$SERVICE_USER" "$INSTALL_DIR/relay-server.js"
chmod 0640 "$INSTALL_DIR/relay-server.js"

cat >"$INSTALL_DIR/package.json" <<'HONGSSH_PACKAGE_EOF'
{
  "name": "hongssh-relay",
  "version": "1.0.0",
  "private": true,
  "dependencies": {
    "ws": "^8.18.0"
  }
}
HONGSSH_PACKAGE_EOF
chown root:"$SERVICE_USER" "$INSTALL_DIR/package.json"
chmod 0640 "$INSTALL_DIR/package.json"

log "Installing ws dependency"
(
  cd "$INSTALL_DIR"
  npm install --omit=dev --no-audit --no-fund
)
chown -R root:"$SERVICE_USER" "$INSTALL_DIR"
find "$INSTALL_DIR" -type d -exec chmod 0750 {} +
find "$INSTALL_DIR" -type f -exec chmod 0640 {} +

umask 077
{
  printf 'PORT=%s\n' "$PORT"
  printf 'HOST_TOKEN=%s\n' "$TOKEN"
  printf "ICE_SERVERS_JSON='%s'\n" "$ICE_JSON"
  if [[ -n "$TLS_CERT_FINAL" ]]; then
    printf "TLS_CERT='%s'\n" "$TLS_CERT_FINAL"
    printf "TLS_KEY='%s'\n" "$TLS_KEY_FINAL"
  fi
} >"$ENV_FILE"
chown root:root "$ENV_FILE"
chmod 0600 "$ENV_FILE"

cat >"$SERVICE_FILE" <<EOF
[Unit]
Description=HongSSH WebRTC signaling relay
Documentation=file://$INSTALL_DIR/relay-server.js
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=$SERVICE_USER
Group=$SERVICE_USER
WorkingDirectory=$INSTALL_DIR
EnvironmentFile=$ENV_FILE
ExecStart=$NODE_BIN $INSTALL_DIR/relay-server.js
Restart=always
RestartSec=3
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=true
ProtectKernelTunables=true
ProtectControlGroups=true
RestrictSUIDSGID=true
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX
ReadOnlyPaths=$INSTALL_DIR
LimitNOFILE=65535
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
EOF
chmod 0644 "$SERVICE_FILE"

if [[ "$OPEN_FIREWALL" -eq 1 ]]; then
  if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q 'Status: active'; then
    ufw allow "${PORT}/tcp" >/dev/null 2>&1 || true
    log "ufw: allowed ${PORT}/tcp"
  fi
  if command -v firewall-cmd >/dev/null 2>&1 && firewall-cmd --state >/dev/null 2>&1; then
    firewall-cmd --permanent --add-port="${PORT}/tcp" >/dev/null 2>&1 || true
    firewall-cmd --reload >/dev/null 2>&1 || true
    log "firewalld: allowed ${PORT}/tcp"
  fi
fi

log "Starting service"
systemctl daemon-reload
systemctl enable "$SERVICE_NAME" >/dev/null 2>&1
systemctl restart "$SERVICE_NAME"

SCHEME="http"
CURL_TLS=()
if [[ -n "$TLS_CERT_FINAL" ]]; then
  SCHEME="https"
  CURL_TLS=(-k)
fi
HEALTH_URL="${SCHEME}://127.0.0.1:${PORT}/health"
HEALTH_OK=0
for _ in $(seq 1 30); do
  if curl -fsS --noproxy '*' "${CURL_TLS[@]}" "$HEALTH_URL" >/tmp/hongssh-relay-health.json 2>/dev/null; then
    HEALTH_OK=1
    break
  fi
  sleep 1
done
if [[ "$HEALTH_OK" -ne 1 ]]; then
  warn "health check failed; recent service logs:"
  journalctl -u "$SERVICE_NAME" --no-pager -n 60 || true
  die "relay did not become healthy"
fi
if ! systemctl is-active --quiet "$SERVICE_NAME"; then
  warn "service is not active; recent logs:"
  journalctl -u "$SERVICE_NAME" --no-pager -n 60 || true
  die "relay service is not active"
fi

